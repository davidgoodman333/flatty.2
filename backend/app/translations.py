def is_already_english(title: str) -> bool:
    """True if the title is already predominantly in English and contains no German indicators."""
    if not title:
        return True
    german_indicators = re.compile(
        r"\b(zimmer|wohnung|wohnungen|wg|whg|altbau|neubau|dachwohnung|möbliert|nachmieter|"
        r"untermiete|befristet|sofort|per sofort|ab sofort|ruhige|helle|schöne|grosszügige|"
        r"zentrale|mit|und|für|im|am|an der|in der|nähe|sanierte|erstbezug|zu vermieten|"
        r"einfamilienhaus|grosszügig|gemütlich|stadtnähe|gesucht|balkon|garten)\b|[äöüÄÖÜß]",
        re.IGNORECASE,
    )
    english_indicators = re.compile(
        r"\b(apartment|flat|room|bedroom|studio|bright|quiet|furnished|available|near|shared flat|"
        r"sublet|spacious|student|cosy|temporary|historic|looking for|flatmate|long-term)\b",
        re.IGNORECASE,
    )
    return bool(english_indicators.search(title)) and not bool(german_indicators.search(title))


def translate_property_title(title: str) -> str:
    """Translates a Swiss property listing title to natural English with high accuracy."""
    if not title or not title.strip():
        return ""
    text = title.strip()
    if is_already_english(text):
        return text

    # Step 1: Normalize fractions like "2 1/2" -> "2.5"
    for pattern, repl in FRACTIONS:
        text = re.sub(pattern, repl, text, flags=re.IGNORECASE)

    # Step 2: Normalize real estate abbreviations (e.g. "3.5-ZW" -> "3.5-room apartment")
    for pattern, repl in ABBREVIATIONS:
        text = re.sub(pattern, repl, text, flags=re.IGNORECASE)

    # Step 3: French multi-word patterns
    for pattern, repl in FRENCH_PATTERNS:
        text = re.sub(pattern, repl, text, flags=re.IGNORECASE)

    # Step 4: Swiss German hot phrases (longest matches first)
    for pattern, repl in HOT_PHRASES:
        text = re.sub(pattern, repl, text, flags=re.IGNORECASE)

    # Step 5: Room and apartment compound types
    for pattern, repl in ROOM_PATTERNS:
        text = re.sub(pattern, repl, text, flags=re.IGNORECASE)

    # Step 6: Word-by-word dictionary translation
    def replace_token(match):
        token = match.group(0)
        low = token.lower()
        if low in BERN_PRESERVED:
            if low == "studentlodge":
                return "studentlodge"
            if low == "wankdorfcity":
                return "WankdorfCity"
            if low == "bäretower":
                return "BäreTower"
            return low.capitalize()
        if low in HOT_WORDS:
            val = HOT_WORDS[low]
            if match.start() == 0:
                return val.capitalize()
            return val.lower()
        return token

    text = re.sub(r"\b[a-zA-ZäöüÄÖÜßéèàâêîôûç]+\b", replace_token, text)

    # Step 7: Clean formatting artifacts
    # Fix room counts and compounds: "3.5 room" -> "3.5-room"
    text = re.sub(r"(\d+(?:\.5)?)\s+(room|person)\b", r"\1-\2", text, flags=re.IGNORECASE)
    # Fix awkward hyphens like "3.5-room-top-floor apartment" -> "3.5-room top-floor apartment"
    text = re.sub(r"(\d+(?:\.5)?-room)-([A-Za-z])", r"\1 \2", text)
    # Fix trailing hyphen before words like "3.5-room-apartment" -> "3.5-room apartment"
    text = re.sub(r"(\d+(?:\.5)?-room)-(apartment|house)\b", r"\1 \2", text, flags=re.IGNORECASE)
    # Clean redundant spaces and punctuation
    text = re.sub(r"\s+", " ", text).strip()
    text = re.sub(r"\s+([,.:;!?])", r"\1", text)
    # Remove leading decorative symbols like "// " or "- "
    text = re.sub(r"^[/\\| -]+", "", text).strip()
    if text:
        text = text[0].upper() + text[1:]
    return text


